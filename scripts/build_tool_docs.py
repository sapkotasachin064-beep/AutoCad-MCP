"""Generate docs/tools.md from the server's registered tools (names, toolsets,
side-effect kinds, backends, descriptions and argument schemas).

    python scripts/build_tool_docs.py          # write docs/tools.md
    python scripts/build_tool_docs.py --check  # fail if it is stale
"""

import asyncio
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
os.environ.pop("AUTOCAD_MCP_TOOLSETS", None)  # document every toolset
os.environ.pop("AUTOCAD_MCP_BACKEND", None)

import server  # noqa: E402
from core import registry  # noqa: E402

KIND_TEXT = {
    "read": "read-only",
    "session": "session state only",
    "write": "changes the drawing or AutoCAD's state, never removes work",
    "destructive": "can remove or overwrite work",
    "external": "writes files or starts processes",
}


def _type(schema: dict) -> str:
    if "anyOf" in schema:
        return " | ".join(_type(s) for s in schema["anyOf"])
    t = schema.get("type", "any")
    if t == "array":
        return f"list[{_type(schema.get('items', {}))}]"
    if t == "object" and "additionalProperties" in schema and isinstance(schema["additionalProperties"], dict):
        return f"dict[str, {_type(schema['additionalProperties'])}]"
    return {"null": "null", "number": "number", "integer": "integer", "string": "string",
            "boolean": "boolean", "object": "object"}.get(t, t)


def build() -> str:
    tools = {t.name: t for t in asyncio.run(server.server.list_tools())}
    caps = registry.capability_map()["tools"]
    specs = registry.specs()
    lines = [
        "# Tool reference",
        "",
        "Generated by `python scripts/build_tool_docs.py` from the registered tools; do not edit by hand.",
        f"{len(tools)} public MCP tools in {len(registry.TOOLSETS)} toolsets. Every tool returns JSON; failures return",
        "an error envelope (`code`, `message`, `recoverable`, `recommended_action`, `details`) -- see",
        "[architecture.md](architecture.md#errors). Tools that change something add a `state` block",
        "(`accepted`, `preflight_passed`, `executed`, `verified`, `saved`).",
        "",
        "| Toolset | Tools | Purpose |",
        "|---|---|---|",
    ]
    by_set = {}
    for name, spec in specs.items():
        by_set.setdefault(spec.toolset, []).append(name)
    for toolset, description in registry.TOOLSETS.items():
        lines.append(f"| `{toolset}` | {len(by_set.get(toolset, []))} | {description} |")
    for toolset in registry.TOOLSETS:
        lines += ["", f"## `{toolset}`", ""]
        for name in sorted(by_set.get(toolset, [])):
            spec, tool, cap = specs[name], tools[name], caps[name]
            backends = ", ".join(cap["backends"]) or "none"
            lines += [f"### `{name}`", "",
                      f"*{spec.title}* -- {KIND_TEXT[spec.kind]}; backends: {backends}"
                      + (f"; note: {spec.notes}" if spec.notes else ""), "",
                      (tool.description or "").strip(), ""]
            props = tool.input_schema.get("properties", {})
            required = set(tool.input_schema.get("required", []))
            if props:
                lines += ["| Argument | Type | Required | Default |", "|---|---|---|---|"]
                for arg, schema in props.items():
                    default = json.dumps(schema["default"]) if "default" in schema else ""
                    lines.append(f"| `{arg}` | {_type(schema)} | {'yes' if arg in required else 'no'} | {default} |")
                lines.append("")
    return "\n".join(lines) + "\n"


def main(check: bool) -> int:
    text = build()
    target = ROOT / "docs" / "tools.md"
    if check:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print(f"stale: {target}")
            return 1
        print("docs/tools.md up to date")
        return 0
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
